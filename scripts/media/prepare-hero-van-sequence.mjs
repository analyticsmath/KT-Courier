import { readdir, mkdir, stat, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import sharp from "sharp";

const root = resolve(import.meta.dirname, "../..");
const sourceDir = join(root, "public/media/public/images/KT_HERO_VAN_19_PNGS");
const outputDir = join(root, "public/media/public/protagonists/hero-van");
const modulePath = join(root, "components/public-v3/home/director/hero-van-sequence.generated.ts");
const files = (await readdir(sourceDir)).filter((file) => file.toLowerCase().endsWith(".png")).sort();
if (files.length !== 19) throw new Error(`Expected 19 PNG frames, found ${files.length}`);

const audited = [];
for (const [index, file] of files.entries()) {
  const match = /^(\d{3})_(\d{3})deg(?:_true_front)?\.png$/i.exec(file);
  if (!match || Number(match[1]) !== index + 1 || Number(match[2]) !== index * 5 || (index === 18) !== file.includes("true_front")) {
    throw new Error(`Unexpected frame order or yaw: ${file}`);
  }
  const path = join(sourceDir, file);
  const metadata = await sharp(path).metadata();
  if (!metadata.hasAlpha || metadata.orientation && metadata.orientation !== 1) throw new Error(`Alpha/orientation invalid: ${file}`);
  if (metadata.width * 3 !== metadata.height * 4) throw new Error(`Expected 4:3 canvas: ${file}`);
  if (audited.length && (metadata.width !== audited[0].width || metadata.height !== audited[0].height)) throw new Error(`Canvas mismatch: ${file}`);
  const { data, info } = await sharp(path).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let bottom = -1;
  for (let y = info.height - 1; y >= 0 && bottom < 0; y--) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * info.channels + 3] > 0) { bottom = y; break; }
    }
  }
  if (bottom < 0) throw new Error(`Empty frame: ${file}`);
  audited.push({ file, yaw: index * 5, width: metadata.width, height: metadata.height, bottom, bytes: (await stat(path)).size });
}
const baselines = audited.map((frame) => frame.bottom / frame.height).sort((a, b) => a - b);
const baseline = baselines[9];
const spread = baselines.at(-1) - baselines[0];
await mkdir(outputDir, { recursive: true });
const frames = [];
for (const frame of audited) {
  const id = `yaw-${String(frame.yaw).padStart(3, "0")}`;
  const desktop = `/media/public/protagonists/hero-van/${id}-desktop.webp`;
  const mobile = `/media/public/protagonists/hero-van/${id}-mobile.webp`;
  const desktopWidth = Math.min(frame.width, frame.yaw === 90 ? 2048 : 1600);
  const mobileWidth = Math.min(frame.width, frame.yaw === 90 ? 1280 : 960);
  for (const [width, url, quality] of [[desktopWidth, desktop, frame.yaw === 90 ? 92 : 90], [mobileWidth, mobile, 90]]) {
    await sharp(join(sourceDir, frame.file))
      .resize({ width, height: width * 3 / 4, fit: "fill", withoutEnlargement: true })
      .webp({ quality, alphaQuality: 100, effort: 6 })
      .toFile(join(root, "public", url.slice(1)));
  }
  frames.push({ id, yaw: frame.yaw, desktopSrc: desktop, mobileSrc: mobile, sourceCanvasWidth: frame.width, sourceCanvasHeight: frame.height, aspectRatio: 4 / 3, sourceFilename: frame.file });
}
const generated = `/* Generated by scripts/media/prepare-hero-van-sequence.mjs. Do not edit manually. */\nexport const HERO_VAN_BASELINE_Y = ${baseline.toFixed(8)};\nexport const HERO_VAN_FRAMES = ${JSON.stringify(frames, null, 2)} as const;\nexport const HERO_VAN_SEQUENCE: readonly string[] = HERO_VAN_FRAMES.map((frame) => frame.id);\n`;
await writeFile(modulePath, generated);
const outputs = (await readdir(outputDir)).filter((file) => file.endsWith(".webp"));
const derivedBytes = (await Promise.all(outputs.map((file) => stat(join(outputDir, file))))).reduce((sum, entry) => sum + entry.size, 0);
console.log(JSON.stringify({ sourceDir, frames: frames.length, dimensions: `${audited[0].width}x${audited[0].height}`, sourceBytes: audited.reduce((sum, frame) => sum + frame.bytes, 0), baseline, baselineSpread: spread, baselineSpreadPercent: spread * 100, derivatives: outputs.length, derivedBytes }, null, 2));
if (spread > .015) console.warn("Source baseline spread exceeds 1.5% of canvas height; review asset registration.");
