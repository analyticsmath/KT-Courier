const scheduledSet = new Set<string>(productionProcessors);

function buildEntry(
  name: ProcessorName,
  spec: Omit<
    ProcessorCoverageEntry,
    "name" | "boundedScan" | "lease" | "retryAndIdempotency" | "cadenceMs"
  > & { readonly scanEnforcement: string },
): ProcessorCoverageEntry {
  const reg = PROCESSOR_REGISTRY[name];
  const cadenceMs =
    (DEFAULT_PRODUCTION_PROCESSOR_CADENCE_MS as Readonly<Record<string, number | undefined>>)[
      name
    ] ?? (scheduledSet.has(name) ? 30_000 : null);
  return Object.freeze({
    name,
    engineeringStatus: spec.engineeringStatus,
    handlerSymbol: spec.handlerSymbol,
    boundedScan: Object.freeze({
      defaultBatchSize: reg.defaultBatchSize,
      maxBatchSize: reg.maxBatchSize,
      enforcement: spec.scanEnforcement,
    }),
    lease: Object.freeze({
      leaseRequired: reg.leaseRequired,
      defaultPartition: reg.defaultPartition,
      authoritySymbol: "lib/processors/lease-authority.ts#acquireProcessorLease",
    }),
    retryAndIdempotency: Object.freeze({
      retryPolicy: reg.retryPolicy,
      idempotencyStrategy: reg.idempotencyStrategy,
    }),
    schedulerRegistration: spec.schedulerRegistration,
    cadenceMs,
    productionActivationGate: spec.productionActivationGate,
    queueHealthIndicator: spec.queueHealthIndicator,
    positiveTest: spec.positiveTest,
    negativeTest: spec.negativeTest,
  });
}

