interface DashboardSidebarProps {
  navItems: NavItem[];
  title?: string;
  footer?: React.ReactNode;
}

function KTSidebarLogo() {
  return (
    <div className="px-5 py-4 border-b border-[var(--kt-soft-border)]">
      <Link
        href="/"
        className="flex items-center gap-3 w-fit focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[var(--kt-signal-cobalt)] rounded-xl"
      >
        <span className="relative flex h-9 w-9 items-center justify-center rounded-xl bg-[var(--kt-ink-navy)] text-white flex-shrink-0">
          <span className="font-display text-xs font-black tracking-normal">KT</span>
          <span
            className="absolute -right-0.5 -top-0.5 h-2.5 w-2.5 rounded-full bg-[var(--kt-solar-amber)] ring-[1.5px] ring-white"
            aria-hidden="true"
          />
        </span>
        <span>
          <span className="block font-display text-sm font-black text-[var(--kt-ink-navy)] leading-none tracking-normal">
            KT Couriers
          </span>
          <span className="block text-[10px] font-extrabold uppercase tracking-wider text-[var(--kt-text-muted)] mt-0.5">
            Courier platform
          </span>
        </span>
      </Link>
    </div>
  );
}

export function DashboardSidebar({
  navItems,
  title,
  footer,
}: DashboardSidebarProps) {
  const pathname = usePathname();

  return (
    <aside className="hidden lg:flex flex-col w-64 flex-shrink-0 bg-[var(--kt-studio-white)] border-r border-[var(--kt-soft-border)] min-h-screen">
      <KTSidebarLogo />

      {title && (
        <div className="px-5 pt-5 pb-1.5">
          <p className="text-[10px] font-extrabold uppercase tracking-widest text-[var(--kt-text-muted)]">
            {title}
          </p>
        </div>
      )}

      <nav
        className="flex-1 px-3 py-3 space-y-0.5"
        aria-label="Dashboard navigation"
      >
        {navItems.map((item) => {
          const isActive =
            pathname === item.href ||
            (pathname.startsWith(item.href + "/") && item.href !== "/");
          return (
            <Link
              key={item.href}
              href={item.href}
              className={cn(
                "group flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-semibold transition-all duration-100",
                isActive
                  ? "bg-[var(--kt-cloud-blue)] text-[var(--kt-signal-cobalt)] font-bold"
                  : "text-[var(--kt-text-muted)] hover:bg-[var(--kt-cool-gray)] hover:text-[var(--kt-ink-navy)]"
              )}
              aria-current={isActive ? "page" : undefined}
            >
              <span
                className={cn(
                  "flex-shrink-0 transition-colors duration-100",
                  isActive
                    ? "text-[var(--kt-signal-cobalt)]"
                    : "text-[var(--kt-text-muted)] group-hover:text-[var(--kt-ink-navy)]"
                )}
              >
                <NavIcon href={item.href} />
              </span>
              <span className="truncate flex-1">{item.label}</span>
              {item.badge !== undefined && (
                <span className="ml-auto text-[10px] font-extrabold bg-[var(--kt-signal-cobalt)] text-white rounded-full px-1.5 py-0.5 min-w-[18px] text-center flex-shrink-0">
                  {item.badge}
                </span>
              )}
            </Link>
          );
        })}
      </nav>

      {footer && (
        <div className="px-3 py-3 border-t border-[var(--kt-soft-border)]">
          {footer}
        </div>
      )}
    </aside>
  );
}
