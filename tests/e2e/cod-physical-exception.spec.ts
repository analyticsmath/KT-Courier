import { expect, test } from "@playwright/test";
import sharp from "sharp";
import { prisma } from "@/lib/db/prisma";
import { codBooking, codReviewer, codState, codTransit, verifyCodDeposit } from "../integration/cod-canonical-support";
import { login } from "./fixtures/auth";

test("independently reviews a reported COD delivery without recording cash", async ({ page }) => {
  test.setTimeout(300_000);
  await page.setViewportSize({ width: 390, height: 900 });
  const fixture = await codBooking(page, "390");
  await verifyCodDeposit(page, fixture);
  await codTransit(fixture);
  const assignment = await prisma.orderAssignment.findFirstOrThrow({ where: { orderId: fixture.order.id, status: "ACCEPTED" } });
  await login(page, fixture.driver.user.email);
  await page.goto(`/driver/assignments/${assignment.id}`);
  const image = await sharp({ create: { width: 48, height: 32, channels: 3, background: "#227799" } }).png().toBuffer();
  await page.getByLabel("Private delivery proof image", { exact: true }).setInputFiles({ name: "synthetic-delivery-evidence.png", mimeType: "image/png", buffer: image });
  const uploadResponse = page.waitForResponse(response => response.url().endsWith("/delivery/proof") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Upload private delivery proof", exact: true }).click();
  const uploaded = await uploadResponse; expect(uploaded.status(), await uploaded.text()).toBe(201);
  const evidence = await uploaded.json() as { evidenceReference: string };
  const before = await codState(fixture.order.id);
  await login(page, "superadmin@ktcouriers.local");
  await page.goto(`/admin/orders/${fixture.order.id}`);
  await page.getByLabel("Private delivery evidence", { exact: true }).selectOption(evidence.evidenceReference);
  await page.getByLabel("Reason", { exact: true }).fill("Synthetic report for independent review");
  const reportResponse = page.waitForResponse(response => response.url().endsWith("/cod-delivery-exception") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Report delivery for review", exact: true }).click();
  const reported = await reportResponse; expect(reported.status(), await reported.text()).toBe(200);
  await expect(page.getByText("A different authorized cash reviewer must review this report.")).toBeVisible();
  const pending = await codState(fixture.order.id);
  expect(pending.order.status).toBe("IN_TRANSIT");
  expect(pending.cod.cashCollected.isZero()).toBe(true);
  expect(pending.journals).toEqual(before.journals);
  const reviewer = await codReviewer();
  const admin = await prisma.user.findUniqueOrThrow({ where: { email: "superadmin@ktcouriers.local" }, select: { passwordHash: true } });
  await prisma.user.update({ where: { id: reviewer.id }, data: { passwordHash: admin.passwordHash } });
  await login(page, reviewer.email);
  await page.goto(`/admin/orders/${fixture.order.id}`);
  await page.getByLabel("Review decision", { exact: true }).selectOption("VERIFY");
  await page.getByLabel("Reason", { exact: true }).fill("Synthetic evidence independently reviewed");
  const reviewResponse = page.waitForResponse(response => response.url().endsWith("/cod-delivery-exception") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Record independent review", exact: true }).click();
  const reviewed = await reviewResponse; expect(reviewed.status(), await reviewed.text()).toBe(200);
  const after = await codState(fixture.order.id);
  expect(after.cod.reconciliationStatus).toBe("PHYSICAL_DELIVERY_VERIFIED");
  expect(after.cod.cashCollected.isZero()).toBe(true);
  expect(after.order.status).toBe("IN_TRANSIT");
  expect(after.journals).toEqual(before.journals);
});
